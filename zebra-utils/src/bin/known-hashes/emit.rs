//! Chunk file emission and `KnownHashListSpec` constant printing.
//!
//! Converts a completed sweep into the chunk files described in
//! [`zebra_chain::parameters::known_hashes::chunk`], verifies them with the
//! same loader Zebra uses, and prints the spec constant that pins them.

use std::{fmt::Write as _, fs, path::Path, sync::Arc};

use color_eyre::eyre::{ensure, Result, WrapErr};

use zebra_chain::{
    block,
    parameters::{
        checkpoint::list::CheckpointList,
        known_hashes::{
            chunk_file_name, chunk_sha256_hex, Chunk, KnownHashList, KnownHashListSpec,
        },
    },
};

/// Writes `blocks` (one `(hash, size hint)` pair per height, from genesis) as
/// chunk files of `chunk_blocks` blocks into `out_dir`, and returns the
/// SHA-256 hex of each chunk.
pub fn emit_chunks(
    out_dir: &Path,
    file_prefix: &str,
    blocks: &[(block::Hash, u8)],
    chunk_blocks: u32,
) -> Result<Vec<String>> {
    ensure!(
        !blocks.is_empty(),
        "the known-hash list must contain at least the genesis block hash",
    );
    ensure!(chunk_blocks > 0, "chunks must hold at least one block");

    let mut chunk_hashes = Vec::new();
    for (index, chunk_blocks_slice) in blocks.chunks(chunk_blocks as usize).enumerate() {
        let start = u32::try_from(index)? * chunk_blocks;
        let bytes = Chunk::encode(block::Height(start), chunk_blocks_slice);

        let path = out_dir.join(chunk_file_name(file_prefix, index));
        fs::write(&path, &bytes).wrap_err_with(|| format!("writing {}", path.display()))?;

        chunk_hashes.push(chunk_sha256_hex(&bytes));
    }

    Ok(chunk_hashes)
}

/// Re-reads the chunk files in `out_dir` with Zebra's loader, checking them
/// against `spec` and `checkpoints`, so the tool never prints a spec that
/// Zebra would reject.
pub fn verify_emitted(
    out_dir: &Path,
    spec: KnownHashListSpec<'_>,
    checkpoints: Arc<CheckpointList>,
) -> Result<()> {
    KnownHashList::open(spec, checkpoints, out_dir)
        .wrap_err("the emitted chunks failed verification")?;

    Ok(())
}

/// Formats the `KnownHashListSpec` constant for `spec`, ready to paste into
/// `zebra-chain`.
///
/// `const_prefix` is the network part of the constant name, for example
/// `MAINNET`.
pub fn spec_constant_block(const_prefix: &str, spec: &KnownHashListSpec<'_>) -> String {
    let mut block = String::new();

    // Writing to a `String` never fails.
    let _ = writeln!(
        block,
        "/// The {const_prefix} known-hash list, generated by the `known-hashes` tool.\n\
         pub const {const_prefix}_KNOWN_HASHES: KnownHashListSpec<'static> = KnownHashListSpec {{\n\
         \x20   max_height: block::Height({}),\n\
         \x20   chunk_blocks: {},\n\
         \x20   file_prefix: \"{}\",\n\
         \x20   chunk_hashes: &[",
        spec.max_height.0, spec.chunk_blocks, spec.file_prefix,
    );
    for chunk_hash in spec.chunk_hashes {
        let _ = writeln!(block, "        \"{chunk_hash}\",");
    }
    let _ = writeln!(block, "    ],\n}};");

    block
}
